import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from architecture_scan import scan


class ArchitectureScanTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name) / 'theme'
        self.root.mkdir()

    def tearDown(self):
        self.temp.cleanup()

    def write(self, path, content):
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content.encode() if isinstance(content, str) else content)

    def test_real_dependencies_ignore_documentation_and_json_headers(self):
        self.write('templates/product.json', '/* generated by Shopify */\n{"sections":{"main":{"type":"main-product"}}}')
        self.write('sections/main-product.liquid', "{% comment %}{% render 'obsolete' %}{% endcomment %}\n{% doc %}{% render 'example' %}{% enddoc %}\n{% render 'buy-buttons' %}\n{{ 'card.css' | asset_url }}")
        self.write('snippets/buy-buttons.liquid', '<button>Buy</button>')
        self.write('assets/card.css', 'button { color: red; }')
        report = scan(self.root)
        targets = {edge['target'] for edge in report['edges']}
        self.assertEqual(targets, {'sections/main-product.liquid', 'snippets/buy-buttons.liquid', 'assets/card.css'})
        self.assertFalse(report['parse_errors'])
        self.assertTrue(all(edge['resolution'] == 'in_scan' for edge in report['edges']))

    def test_partial_sample_does_not_call_unread_live_asset_missing(self):
        self.write('snippets/gallery.liquid', "{{ 'gallery.js' | asset_url }}\n{% render 'dynamic-not-located' %}")
        manifest = {'theme_id': 'test', 'files': [{'filename': 'assets/gallery.js', 'checksumMd5': 'not-read'}]}
        report = scan(self.root, manifest, 'partial_sample', 'fixture')
        resolutions = {edge['target']: edge['resolution'] for edge in report['edges']}
        self.assertEqual(resolutions['assets/gallery.js'], 'in_live_manifest_only')
        self.assertEqual(resolutions['snippets/dynamic-not-located.liquid'], 'not_resolved')
        self.assertEqual(report['coverage'], 'partial_sample')

    def test_hashes_preserve_binary_and_newline_differences(self):
        self.write('assets/picture.png', b'\x89PNG\r\n\x00\xff')
        self.write('assets/a.js', b'a\r\n')
        manifest = {'files': [
            {'filename': 'assets/picture.png', 'checksumMd5': hashlib.md5(b'\x89PNG\r\n\x00\xff').hexdigest()},
            {'filename': 'assets/a.js', 'checksumMd5': hashlib.md5(b'a\n').hexdigest()},
        ]}
        report = scan(self.root, manifest)
        self.assertEqual(report['parity']['equal'], ['assets/picture.png'])
        self.assertEqual(report['parity']['different'], ['assets/a.js'])
        self.assertFalse(report['parse_errors'])

    def test_cli_fails_incomplete_snapshot_and_does_not_change_sources(self):
        self.write('assets/a.js', 'const a = 1;')
        before = (self.root / 'assets/a.js').read_bytes()
        manifest = Path(self.temp.name) / 'manifest.json'
        manifest.write_text(json.dumps({'files': [{'filename': 'assets/b.js', 'checksumMd5': 'missing'}]}))
        out = Path(self.temp.name) / 'report'
        result = subprocess.run([sys.executable, str(Path(__file__).with_name('architecture_scan.py')),
                                 '--theme-root', str(self.root), '--manifest', str(manifest),
                                 '--source-label', 'fixture', '--coverage', 'full_snapshot',
                                 '--output-dir', str(out), '--require-parity'], capture_output=True)
        self.assertEqual(result.returncode, 2)
        self.assertTrue((out / 'inventory.json').is_file())
        self.assertEqual((self.root / 'assets/a.js').read_bytes(), before)

    def test_cli_refuses_output_in_source_or_root(self):
        self.write('README.md', 'preserve project documentation')
        for output in (self.root, self.root / 'assets/reports'):
            result = subprocess.run([sys.executable, str(Path(__file__).with_name('architecture_scan.py')),
                                     '--theme-root', str(self.root), '--source-label', 'fixture',
                                     '--coverage', 'unknown', '--output-dir', str(output)], capture_output=True)
            self.assertEqual(result.returncode, 2)
        self.assertEqual((self.root / 'README.md').read_text(), 'preserve project documentation')


if __name__ == '__main__':
    unittest.main()
